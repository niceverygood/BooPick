import type { ListingRow } from "./scoring";
import type { ParsedQuery } from "./parsed-query-types";

const M2 = 3.3058;
const m2 = (p: number) => Math.round(p * M2 * 10) / 10;

function makeRow(
  id: number,
  o: {
    article_no?: string;
    지역: string;
    공급평: number;
    전용평?: number; // 기본 0.62
    해당층: string;
    전체층: string;
    보증금: number; // 만원
    월세: number; // 만원
    관리비?: number; // 만원
    현재업종?: string;
    추천업종?: string;
    간략설명?: string;
    설명: string;
    주소: string;
    사용승인일: string; // YYYY-MM-DD
  }
): ListingRow {
  const 전용 = o.전용평 ?? Math.round(o.공급평 * 0.62 * 10) / 10;
  return {
    id,
    article_no: o.article_no ?? null,
    지역: o.지역,
    공급_m2: m2(o.공급평),
    전용_m2: m2(전용),
    공급_평: o.공급평,
    전용_평: 전용,
    해당층: o.해당층,
    전체층: o.전체층,
    보증금: o.보증금 * 10_000,
    월세: o.월세 * 10_000,
    관리비: (o.관리비 ?? 0) * 10_000,
    현재업종: o.현재업종 ?? null,
    추천업종: o.추천업종 ?? null,
    간략설명: o.간략설명 ?? null,
    설명: o.설명,
    주소: o.주소,
    사용승인일: o.사용승인일,
    중개사무소명: "데모 공인중개사사무소",
  };
}

